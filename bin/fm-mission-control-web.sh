#!/usr/bin/env bash
# fm-mission-control-web.sh - Mission Control's public page, a static snapshot anyone can open.
#
# The public page shows the Office, Calendar, Projects and Team views to any
# visitor; the Tasks, Approvals, Memory, Docs and System tabs show a lock and are
# never written into the page. It is built from this home's records by
# bin/fm_mission_control_web.py, which owns what the snapshot may contain (an
# allow-list: public names, working or asleep, per-project counts, per-day
# calendar counts, never titles, notes, paths, links or ids) and writes the
# folder. The office moves in the visitor's browser between builds, so the Mac
# only works for the few seconds each build takes. Nothing on the page can
# change anything or reach an agent.
#
# Commands:
#   build <dir> [--agents <file>]
#                           write the page folder (index.html, style.css,
#                           app.js, snapshot.json, .nojekyll) into <dir>;
#                           --agents is a saved `herdr agent list` in place of
#                           asking Herdr once
#   publish <dir> [--agents <file>]
#                           build, then send the page to public_page.host.
#                           github (the default): when <dir> is the top of a
#                           git checkout whose origin is public_page.repository,
#                           commit only the page's files and push them; an
#                           unchanged folder commits nothing and pushes only a
#                           commit an earlier run could not push. A <dir> that
#                           is not a git checkout is built and left alone; a
#                           checkout of any other repository is refused.
#                           cloudflare: write snapshot.json to the Workers KV
#                           namespace "<project>-snapshot" when it changed, and
#                           deploy the page code (index.html, style.css, app.js
#                           and the Pages Function in
#                           bin/mission-control-web/functions/ that serves
#                           /snapshot.json from KV) to the Pages project
#                           public_page.project with wrangler, to the project's
#                           production branch, only when that code changed,
#                           since Pages limits deploys a month. The namespace
#                           and project are created when absent.
#                           <dir>/.cloudflare-published records what Cloudflare
#                           holds and the page's address, so an upload that
#                           failed is retried on the next run; delete it to
#                           upload both again.
#   install <dir>           write ~/Library/LaunchAgents/com.firstmate.mission-control-web.plist,
#                           which runs `publish <dir>` every public_page.every_minutes
#                           minutes and at login, and load it with
#                           `launchctl bootstrap gui/<uid>`; it first refuses
#                           an unknown host and, for cloudflare, an invalid
#                           project or missing credentials
#   uninstall               `launchctl bootout` the job and remove the plist
#   status                  report whether the job is loaded, its folder, the
#                           snapshot's time, where it is published (the page's
#                           address on Cloudflare) and the last log line
#
# Settings: config/mission-control.json `public_page` in the home, optional:
# host ("github" or "cloudflare"), repository ("owner/name" of the GitHub Pages
# repository), project (the Cloudflare Pages project, default mission-control),
# every_minutes (default 5) and heartbeat_minutes (default 60);
# bin/fm_mission_control_web.py's header owns their meaning. The project names
# come from the same file's `names`, as on Mission Control. Run install again
# after changing every_minutes.
#
# Each run of the page is generated by this tracked code, so an update to
# Mission Control reaches the public page on its next build with no other step.
#
# Cloudflare credentials: CLOUDFLARE_API_TOKEN (Pages Edit and Workers KV
# Edit) and CLOUDFLARE_ACCOUNT_ID, read only from the home's .env, the same
# file the scheduled job reads. The token reaches curl on standard input and
# wrangler in its environment only; it is never printed, logged or written to a
# file.
#
# Environment: FM_HOME selects the home whose crew is shown. FM_MC_HERDR
# replaces the herdr command, as for Mission Control. FM_MCW_AGENT_DIR
# relocates the LaunchAgents directory and FM_MCW_STATE_DIR the job's log.
set -eu

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
FM_HOME="${FM_HOME:-${FM_ROOT_OVERRIDE:-$FM_ROOT}}"
FM_HOME="$(cd "$FM_HOME" && pwd)"
CONFIG="$FM_HOME/config"
STATE="${FM_MCW_STATE_DIR:-$FM_HOME/state}"
PY="$SCRIPT_DIR/fm_mission_control_web.py"
LABEL=com.firstmate.mission-control-web
AGENT_DIR="${FM_MCW_AGENT_DIR:-$HOME/Library/LaunchAgents}"
PLIST="$AGENT_DIR/$LABEL.plist"
LOG="$STATE/mission-control-web.log"
CF_API=https://api.cloudflare.com/client/v4
CF_KEY=snapshot.json
CF_RECORD=.cloudflare-published
CF_PAGE_FILES=(index.html style.css app.js)
CF_COMPAT_DATE=2025-09-01
if command -v shasum >/dev/null 2>&1; then SHA=(shasum -a 256); else SHA=(sha256sum); fi

usage() {
  sed -n '2,/^set -eu$/p' "${BASH_SOURCE[0]}" | sed -e '/^set -eu$/d' -e 's/^# \{0,1\}//'
}

die() { printf 'fm-mission-control-web: %s\n' "$1" >&2; exit 1; }
say() { printf 'fm-mission-control-web: %s\n' "$1"; }

setting() {  # <key>
  python3 "$PY" setting "$1" --config-dir "$CONFIG"
}

cmd_build() {  # <dir> [--agents <file>]
  local dir=${1:-}
  [ -n "$dir" ] || die "build needs a folder"
  shift
  local extra=()
  while [ $# -gt 0 ]; do
    case "$1" in
      --agents) extra+=(--agents "${2:?--agents needs a file}"); shift ;;
      *) die "unknown option: $1" ;;
    esac
    shift
  done
  mkdir -p "$dir"
  python3 "$PY" build --home "$FM_HOME" --config-dir "$CONFIG" --out "$dir" \
    --herdr "${FM_MC_HERDR:-herdr}" ${extra[@]+"${extra[@]}"}
}

repo_of_url() {  # <remote url> - prints owner/name, lowercased, without .git
  printf '%s\n' "$1" | sed -E -e 's#\.git/?$##' -e 's#/$##' -e 's#^.*[:/]([^/:]+/[^/:]+)$#\1#' | tr '[:upper:]' '[:lower:]'
}

cmd_publish() {  # <dir> [--agents <file>]
  local dir=${1:-} host
  [ -n "$dir" ] || die "publish needs a folder"
  host=$(known_host)
  [ "$host" != cloudflare ] || cf_credentials
  cmd_build "$@"
  dir="$(cd "$dir" && pwd -P)"
  case "$host" in
    github) publish_github "$dir" ;;
    cloudflare) publish_cloudflare "$dir" ;;
  esac
}

known_host() {  # prints public_page.host, refusing one publish does not know
  local host
  host=$(setting host)
  case "$host" in
    github|cloudflare) printf '%s\n' "$host" ;;
    *) die "public_page.host in config/mission-control.json is \"$host\"; use \"github\" or \"cloudflare\"" ;;
  esac
}

known_project() {  # prints public_page.project, refusing a name Cloudflare Pages does not accept
  local project
  project=$(setting project)
  [[ "$project" =~ ^[a-z0-9][a-z0-9-]{0,57}$ ]] \
    || die "public_page.project in config/mission-control.json is \"$project\"; use lowercase letters, digits and hyphens"
  printf '%s\n' "$project"
}

publish_github() {  # <built dir>
  local dir=$1 repo top origin files=() f ahead
  repo=$(setting repository)
  top=$(git -C "$dir" rev-parse --show-toplevel 2>/dev/null || true)
  if [ -z "$top" ] || [ "$(cd "$top" && pwd -P)" != "$dir" ]; then
    say "built $dir; it is not the top of a git checkout, so nothing was pushed"
    return 0
  fi
  [ -n "$repo" ] || die "$dir is a git checkout but public_page.repository is not set in config/mission-control.json; nothing was pushed"
  origin=$(git -C "$dir" remote get-url origin 2>/dev/null || true)
  if [ "$(repo_of_url "$origin")" != "$(printf '%s' "$repo" | tr '[:upper:]' '[:lower:]')" ]; then
    die "$dir pushes to ${origin:-no origin}, not $repo; nothing was pushed"
  fi
  while IFS= read -r f; do files+=("$f"); done < <(python3 "$PY" files)
  git -C "$dir" add -- "${files[@]}"
  if ! git -C "$dir" diff --cached --quiet -- "${files[@]}"; then
    git -C "$dir" commit -q -m "Update Mission Control snapshot" -- "${files[@]}" \
      || die "git commit failed in $dir"
  fi
  ahead=$(git -C "$dir" rev-list --count '@{upstream}..HEAD' 2>/dev/null || echo unknown)
  if [ "$ahead" = 0 ]; then
    say "unchanged; nothing to push"
    return 0
  fi
  if [ "$ahead" = unknown ]; then
    git -C "$dir" push -q -u origin HEAD || die "git push failed from $dir"
  else
    git -C "$dir" push -q origin HEAD || die "git push failed from $dir"
  fi
  say "pushed $(git -C "$dir" rev-parse --short HEAD) to $repo"
}

# --- Cloudflare ----------------------------------------------------------------
# The token and account id live only in shell variables: the token reaches curl
# on its standard input and wrangler in its environment, never a command line,
# the log or a file.

cf_credentials() {  # sets CF_TOKEN and CF_ACCOUNT from the home's .env
  CF_TOKEN=$(env_value CLOUDFLARE_API_TOKEN)
  CF_ACCOUNT=$(env_value CLOUDFLARE_ACCOUNT_ID)
  [ -n "$CF_TOKEN" ] || die "CLOUDFLARE_API_TOKEN is not set in $FM_HOME/.env"
  [ -n "$CF_ACCOUNT" ] || die "CLOUDFLARE_ACCOUNT_ID is not set in $FM_HOME/.env"
  printf '%s' "$CF_TOKEN" | grep -Eq '^[A-Za-z0-9_-]+$' \
    || die "CLOUDFLARE_API_TOKEN in $FM_HOME/.env does not look like an API token"
  printf '%s' "$CF_ACCOUNT" | grep -Eq '^[0-9a-fA-F]{32}$' \
    || die "CLOUDFLARE_ACCOUNT_ID in $FM_HOME/.env does not look like an account id"
}

env_value() {  # <name> - its last assignment in the home's .env
  local name=$1
  if [ -f "$FM_HOME/.env" ]; then
    sed -n -E "s/^[[:space:]]*(export[[:space:]]+)?${name}[[:space:]]*=[[:space:]]*//p" "$FM_HOME/.env" | tail -n 1 \
      | sed -E -e 's/[[:space:]]+$//' -e 's/^"(.*)"$/\1/' -e "s/^'(.*)'\$/\1/" | tr -d '\n'
  fi
}

cf_api() {  # <method> <path under the account> <response file> [curl args...] - prints the HTTP status
  local method=$1 path=$2 out=$3
  shift 3
  printf 'header = "Authorization: Bearer %s"\n' "$CF_TOKEN" \
    | curl -sS --config - -X "$method" -o "$out" -w '%{http_code}' \
      "$CF_API/accounts/$CF_ACCOUNT$path" "$@"
}

cf_ok() {  # <status> <response file>
  [ "$1" = 200 ] && jq -e '.success == true' "$2" >/dev/null 2>&1
}

cf_errors() {  # <response file>
  jq -r '[.errors[]? | .message // empty] | join("; ") | if . == "" then "no reason given" else . end' "$1" 2>/dev/null \
    || echo "no reason given"
}

cf_namespace() {  # <title> - prints the id of the Workers KV namespace with that title, creating it when absent
  local title=$1 page=1 code id resp="$WORK/namespaces.json"
  while :; do
    code=$(cf_api GET "/storage/kv/namespaces?per_page=100&page=$page" "$resp" || true)
    cf_ok "$code" "$resp" || die "could not list Workers KV namespaces (HTTP $code): $(cf_errors "$resp")"
    id=$(jq -r --arg t "$title" '[.result[]? | select(.title == $t) | .id][0] // empty' "$resp")
    if [ -n "$id" ]; then
      printf '%s\n' "$id"
      return 0
    fi
    [ "$(jq '.result | length' "$resp")" -ge 100 ] || break
    page=$((page + 1))
  done
  code=$(cf_api POST /storage/kv/namespaces "$resp" -H 'Content-Type: application/json' \
    --data "$(jq -cn --arg t "$title" '{title: $t}')" || true)
  cf_ok "$code" "$resp" || die "could not create the Workers KV namespace $title (HTTP $code): $(cf_errors "$resp")"
  jq -r '.result.id' "$resp"
}

cf_project() {  # <name> - creates the Pages project when it does not exist; leaves it in $WORK/project.json
  local name=$1 code resp="$WORK/project.json"
  code=$(cf_api GET "/pages/projects/$name" "$resp" || true)
  cf_ok "$code" "$resp" && return 0
  [ "$code" = 404 ] || die "could not look up the Pages project $name (HTTP $code): $(cf_errors "$resp")"
  code=$(cf_api POST /pages/projects "$resp" -H 'Content-Type: application/json' \
    --data "$(jq -cn --arg n "$name" '{name: $n, production_branch: "main"}')" || true)
  cf_ok "$code" "$resp" || die "could not create the Pages project $name (HTTP $code): $(cf_errors "$resp")"
  say "created the Pages project $name"
}

record_get() {  # <dir> <key> - from the folder's record of what Cloudflare holds
  sed -n "s/^$2=//p" "$1/$CF_RECORD" 2>/dev/null | tail -n 1
}

record_set() {  # <dir> <key> <value>
  { grep -v "^$2=" "$1/$CF_RECORD" 2>/dev/null || true; printf '%s=%s\n' "$2" "$3"; } > "$1/$CF_RECORD.tmp"
  mv "$1/$CF_RECORD.tmp" "$1/$CF_RECORD"
}

digest() {  # <file>... - one sha256 over the files' names and bytes
  local f
  for f in "$@"; do printf '%s\n' "${f##*/}"; cat "$f"; done | "${SHA[@]}" | cut -d' ' -f1
}

publish_cloudflare() {  # <built dir> - after cf_credentials
  local dir=$1 project title ns code stage page snap f url branch done_=()
  project=$(known_project)
  title="$project-snapshot"
  WORK=$(mktemp -d "${TMPDIR:-/tmp}/fm-mcw.XXXXXX")
  # shellcheck disable=SC2064 # WORK is fixed for this run.
  trap "rm -rf '$WORK'" EXIT

  ns=$(record_get "$dir" namespace)
  case "$ns" in
    "$title:"?*) ns=${ns#"$title:"} ;;
    *)
      ns=$(cf_namespace "$title") || exit 1
      record_set "$dir" namespace "$title:$ns"
      ;;
  esac

  # The snapshot first, so a first deploy never serves an empty route.
  printf '%s\n' "$ns" > "$WORK/namespace"
  snap=$(digest "$WORK/namespace" "$dir/$CF_KEY")
  if [ "$snap" != "$(record_get "$dir" snapshot)" ]; then
    code=$(cf_api PUT "/storage/kv/namespaces/$ns/values/$CF_KEY" "$WORK/put.json" \
      -H 'Content-Type: application/octet-stream' --data-binary "@$dir/$CF_KEY" || true)
    if ! cf_ok "$code" "$WORK/put.json"; then
      record_set "$dir" namespace ""
      die "could not write the snapshot to Workers KV (HTTP $code): $(cf_errors "$WORK/put.json")"
    fi
    record_set "$dir" snapshot "$snap"
    done_+=("wrote the snapshot to Workers KV")
  fi

  stage="$WORK/stage"
  mkdir -p "$stage/public" "$stage/functions"
  for f in "${CF_PAGE_FILES[@]}"; do cp "$dir/$f" "$stage/public/$f"; done
  cp "$SCRIPT_DIR/mission-control-web/functions/$CF_KEY.js" "$stage/functions/$CF_KEY.js"
  cat > "$stage/wrangler.toml" <<EOF
name = "$project"
pages_build_output_dir = "public"
compatibility_date = "$CF_COMPAT_DATE"

[[kv_namespaces]]
binding = "SNAPSHOT"
id = "$ns"
EOF
  page=$(digest "$stage/wrangler.toml" "$stage/functions/$CF_KEY.js" "${CF_PAGE_FILES[@]/#/$stage/public/}")
  if [ "$page" != "$(record_get "$dir" page)" ]; then
    cf_project "$project"
    branch=$(jq -r '.result.production_branch // empty' "$WORK/project.json")
    [ -n "$branch" ] || die "the Pages project $project names no production branch"
    if ! (cd "$stage" && CLOUDFLARE_API_TOKEN="$CF_TOKEN" CLOUDFLARE_ACCOUNT_ID="$CF_ACCOUNT" \
        WRANGLER_SEND_METRICS=false wrangler pages deploy public --project-name "$project" \
        --branch "$branch" --commit-dirty=true) > "$WORK/deploy.log" 2>&1; then
      tail -n 5 "$WORK/deploy.log" >&2
      die "wrangler could not deploy the page to the Pages project $project"
    fi
    record_set "$dir" page "$page"
    url=$(jq -r '.result.subdomain // empty' "$WORK/project.json")
    [ -z "$url" ] || record_set "$dir" url "https://$url"
    done_+=("deployed the page")
  fi

  if [ "${#done_[@]}" = 0 ]; then
    say "unchanged; nothing to upload"
  else
    url=$(record_get "$dir" url)
    say "$(printf '%s and ' "${done_[@]}" | sed 's/ and $//') for ${url:-the Pages project $project}"
  fi
}

plist_escape() {  # <text>
  printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'
}

agent_loaded() {
  launchctl print "gui/$(id -u)/$LABEL" >/dev/null 2>&1
}

cmd_install() {  # <dir>
  local dir=${1:-} every uid host
  [ -n "$dir" ] || die "install needs the folder to publish"
  [ -d "$dir" ] || die "no such folder: $dir"
  dir="$(cd "$dir" && pwd -P)"
  host=$(known_host)
  if [ "$host" = cloudflare ]; then
    known_project >/dev/null
    cf_credentials
  fi
  every=$(setting every_minutes)
  uid=$(id -u)
  mkdir -p "$AGENT_DIR" "$STATE"
  cat > "$PLIST" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>$LABEL</string>
  <key>ProgramArguments</key>
  <array>
    <string>/bin/bash</string>
    <string>$(plist_escape "$SCRIPT_DIR/fm-mission-control-web.sh")</string>
    <string>publish</string>
    <string>$(plist_escape "$dir")</string>
  </array>
  <key>EnvironmentVariables</key>
  <dict>
    <key>FM_HOME</key><string>$(plist_escape "$FM_HOME")</string>
    <key>HOME</key><string>$(plist_escape "$HOME")</string>
    <key>PATH</key><string>$(plist_escape "$PATH")</string>
    <key>LANG</key><string>en_US.UTF-8</string>
  </dict>
  <key>WorkingDirectory</key><string>$(plist_escape "$FM_HOME")</string>
  <key>StandardOutPath</key><string>$(plist_escape "$LOG")</string>
  <key>StandardErrorPath</key><string>$(plist_escape "$LOG")</string>
  <key>StartInterval</key><integer>$((every * 60))</integer>
  <key>RunAtLoad</key><true/>
  <key>LowPriorityIO</key><true/>
  <key>ProcessType</key><string>Background</string>
</dict>
</plist>
EOF
  plutil -lint "$PLIST" >/dev/null || die "the written plist does not validate: $PLIST"
  launchctl bootout "gui/$uid/$LABEL" >/dev/null 2>&1 || true
  launchctl bootstrap "gui/$uid" "$PLIST" || die "launchctl bootstrap refused $PLIST"
  say "installed; publishes $dir every $every minutes (log: $LOG)"
}

cmd_uninstall() {
  launchctl bootout "gui/$(id -u)/$LABEL" >/dev/null 2>&1 || true
  rm -f "$PLIST"
  if agent_loaded; then
    die "launchctl still lists $LABEL after bootout"
  fi
  say "uninstalled"
}

cmd_status() {
  local dir=""
  if agent_loaded; then
    echo "schedule: loaded, every $(setting every_minutes) minutes ($LABEL)"
  else
    echo "schedule: not loaded"
  fi
  if [ -f "$PLIST" ]; then
    dir=$(plutil -extract ProgramArguments.3 raw -o - "$PLIST" 2>/dev/null || true)
  fi
  if [ -n "$dir" ]; then
    echo "folder: $dir"
    if [ -f "$dir/snapshot.json" ]; then
      echo "snapshot: $(jq -r '.generated_at' "$dir/snapshot.json" 2>/dev/null || echo unreadable)"
    fi
  fi
  case "$(setting host)" in
    cloudflare)
      echo "host: Cloudflare Pages project $(setting project)"
      if [ -n "$dir" ] && [ -n "$(record_get "$dir" url)" ]; then
        echo "address: $(record_get "$dir" url)"
      fi
      ;;
    *) echo "repository: $(setting repository)" ;;
  esac
  if [ -f "$LOG" ]; then
    echo "last log line: $(tail -n 1 "$LOG")"
  fi
}

case "${1:-}" in
  build) shift; cmd_build "$@" ;;
  publish) shift; cmd_publish "$@" ;;
  install) shift; cmd_install "$@" ;;
  uninstall) shift; cmd_uninstall ;;
  status) shift; cmd_status ;;
  -h|--help|help) usage ;;
  *) usage >&2; exit 2 ;;
esac
